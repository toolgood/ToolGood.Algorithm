// chebyshevA 对应 C# Evaluate.ChebyshevA（系数最高次在前）。
func chebyshevA(coefficients []float64, x float64) float64 {
	p := 0
	b0 := coefficients[p]
	p++
	b1 := 0.0
	var b2 float64
	for i := len(coefficients) - 1; i > 0; i-- {
		b2 = b1
		b1 = b0
		b0 = x*b1 - b2 + coefficients[p]
		p++
	}
	return 0.5 * (b0 - b2)
}

func besselI0(x float64) float64 {
	x = math.Abs(x)
	if x <= 8 {
		y := x/2 - 2
		return math.Exp(x) * chebyshevA(besselI0A, y)
	}
	x1 := 32/x - 2
	return math.Exp(x) * chebyshevA(besselI0B, x1) / math.Sqrt(x)
}

func besselI1(x float64) float64 {
	z := math.Abs(x)
	var v float64
	if z <= 8 {
		y := z/2 - 2
		v = chebyshevA(besselI1A, y) * z * math.Exp(z)
	} else {
		x1 := 32/z - 2
		v = math.Exp(z) * chebyshevA(besselI1B, x1) / math.Sqrt(z)
	}
	if x < 0 {
		return -v
	}
	return v
}

func besselK0(x float64) float64 {
	if x <= 2 {
		y := x*x - 2
		return chebyshevA(besselK0A, y) - math.Log(0.5*x)*besselI0(x)
	}
	z := 8/x - 2
	return math.Exp(-x) * chebyshevA(besselK0B, z) / math.Sqrt(x)
}

func besselK1(x float64) float64 {
	if x <= 2 {
		y := x*x - 2
		return math.Log(0.5*x)*besselI1(x) + chebyshevA(besselK1A, y)/x
	}
	x1 := 8/x - 2
	return math.Exp(-x) * chebyshevA(besselK1B, x1) / math.Sqrt(x)
}

// besselI 对应 C# SpecialFunctions.BesselI（整数阶第一类修正贝塞尔函数）。
func besselI(n int, x float64) float64 {
	if x < 0 {
		if n%2 == 0 {
			return besselI(n, -x)
		}
		return -besselI(n, -x)
	}
	if n < 0 {
		n = -n
	}
	if x == 0 || x < 1e-10 {
		if n == 0 {
			return 1
		}
		return 0
	}
	if x > 700 {
		factor := math.Exp(x) / math.Sqrt(2*math.Pi*x)
		return factor * (1 - (4*float64(n)*float64(n)-1)/(8*x))
	}
	if n == 0 {
		return besselI0(x)
	}
	if n == 1 {
		return besselI1(x)
	}
	// x <= 700 且阶数极大时 I_n 已下溢为 0，直接返回以避免超长循环
	if n > 100000 {
		return 0
	}
	i0 := besselI0(x)
	i1 := besselI1(x)
	result := 0.0
	for k := 1; k < n; k++ {
		result = i0 - 2*float64(k)/x*i1
		i0, i1 = i1, result
	}
	return i1
}

// besselK 对应 C# SpecialFunctions.BesselK（整数阶第二类修正贝塞尔函数）。
func besselK(n int, x float64) float64 {
	if n < 0 {
		n = -n
	}
	if n == 0 {
		return besselK0(x)
	}
	if n == 1 {
		return besselK1(x)
	}
	// 阶数极大时 K_n 已上溢，直接返回 +Inf（调用方转成函数错误），避免超长循环
	if n > 100000 {
		return math.Inf(1)
	}
	k0 := besselK0(x)
	k1 := besselK1(x)
	result := 0.0
	for k := 1; k < n; k++ {
		result = k0 + 2*float64(k)/x*k1
		k0, k1 = k1, result
		if math.IsInf(result, 0) || math.IsNaN(result) {
			return result
		}
	}
	return k1
}

func besselJ0(x float64) float64 {
	ax := math.Abs(x)
	if ax < 8 {
		y1 := x * x
		ans1 := 57568490574.0 + y1*(-13362590354.0+y1*(651619640.7+y1*(-11214424.18+y1*(77392.33017+y1*(-184.9052456)))))
		ans2 := 57568490411.0 + y1*(1029532985.0+y1*(9494680.718+y1*(59272.64853+y1*(267.8532712+y1))))
		return ans1 / ans2
	}
	z := 8 / ax
	y2 := z * z
	xx := ax - 0.78539816339744830962
	ans3 := 1.0 + y2*(-0.1098628627e-2+y2*(0.2734510407e-4+y2*(-0.2073370639e-5+y2*0.2093887211e-6)))
	ans4 := -0.1562499995e-1 + y2*(0.1430488765e-3+y2*(-0.6911147651e-5+y2*(0.7621095161e-6-y2*0.934935152e-7)))
	return math.Sqrt(0.63661977236758134308/ax) * (math.Cos(xx)*ans3 - z*math.Sin(xx)*ans4)
}

func besselJ1(x float64) float64 {
	ax := math.Abs(x)
	if ax < 8 {
		y1 := x * x
		ans1 := x * (72362614232.0 + y1*(-7895059235.0+y1*(242396853.1+y1*(-2972611.439+y1*(15704.48260+y1*(-30.16036606))))))
		ans2 := 144725228442.0 + y1*(2300535178.0+y1*(18583304.74+y1*(99447.43394+y1*(376.9991397+y1))))
		return ans1 / ans2
	}
	z := 8 / ax
	y2 := z * z
	xx := ax - 2.35619449019234492885
	ans3 := 1.0 + y2*(0.183105e-2+y2*(-0.3516396496e-4+y2*(0.2457520174e-5+y2*(-0.240337019e-6))))
	ans4 := 0.04687499995 + y2*(-0.2002690873e-3+y2*(0.8449199096e-5+y2*(-0.88228987e-6+y2*0.105787412e-6)))
	ans := math.Sqrt(0.63661977236758134308/ax) * (math.Cos(xx)*ans3 - z*math.Sin(xx)*ans4)
	if x < 0 {
		return -ans
	}
	return ans
}

func besselY0(x float64) float64 {
	if x < 8 {
		y1 := x * x
		ans1 := -2957821389.0 + y1*(7062834065.0+y1*(-512359803.6+y1*(10879881.29+y1*(-86327.92757+y1*228.4622733))))
		ans2 := 40076544269.0 + y1*(745249964.8+y1*(7189466.438+y1*(47447.26470+y1*(226.1030244+y1))))
		return ans1/ans2 + 0.63661977236758134308*besselJ0(x)*math.Log(x)
	}
	z := 8 / x
	y2 := z * z
	xx := x - 0.78539816339744830962
	ans3 := 1.0 + y2*(-0.1098628627e-2+y2*(0.2734510407e-4+y2*(-0.2073370639e-5+y2*0.2093887211e-6)))
	ans4 := -0.1562499995e-1 + y2*(0.1430488765e-3+y2*(-0.6911147651e-5+y2*(0.7621095161e-6-y2*0.934935152e-7)))
	return math.Sqrt(0.63661977236758134308/x) * (math.Sin(xx)*ans3 + z*math.Cos(xx)*ans4)
}

func besselY1(x float64) float64 {
	if x < 8 {
		y1 := x * x
		ans1 := x * (-0.4900604943e13 + y1*(0.1275274390e13+y1*(-0.5153438139e11+y1*(0.7349264551e9+y1*(-0.4237922726e7+y1*0.8511937935e4)))))
		ans2 := 0.2499580570e14 + y1*(0.4244419664e12+y1*(0.3733650367e10+y1*(0.2245904002e8+y1*(0.1020426050e6+y1*(0.3549632885e3+y1)))))
		return ans1/ans2 + 0.63661977236758134308*(besselJ1(x)*math.Log(x)-1/x)
	}
	z := 8 / x
	y2 := z * z
	xx := x - 2.35619449019234492885
	ans3 := 1.0 + y2*(0.183105e-2+y2*(-0.3516396496e-4+y2*(0.2457520174e-5+y2*(-0.240337019e-6))))
	ans4 := 0.04687499995 + y2*(-0.2002690873e-3+y2*(0.8449199096e-5+y2*(-0.88228987e-6+y2*0.105787412e-6)))
	return math.Sqrt(0.63661977236758134308/x) * (math.Sin(xx)*ans3 + z*math.Cos(xx)*ans4)
}

// besselJ 对应 C# SpecialFunctions.BesselJ（整数阶第一类贝塞尔函数）。
func besselJ(n int, x float64) float64 {
	if x == 0 {
		if n == 0 {
			return 1
		}
		return 0
	}
	if n < 0 {
		n = -n
	}
	ax := math.Abs(x)
	if ax < 1e-10 {
		if n == 0 {
			return 1
		}
		return 0
	}
	if n == 0 {
		return besselJ0(x)
	}
	if n == 1 {
		return besselJ1(x)
	}
	if ax > float64(n) {
		j0 := besselJ0(x)
		j1 := besselJ1(x)
		result := 0.0
		for k := 1; k < n; k++ {
			result = (2*float64(k)/x)*j1 - j0
			j0, j1 = j1, result
		}
		return j1
	}
	// Miller 向下递推，避免 n > |x| 时向上递推发散（阶数极大时 J_n 已下溢为 0）
	if n > 100000 {
		return 0
	}
	m := int(1.5*float64(n) + 10)
	values := make([]float64, m+2)
	values[m] = 1
	for k := m; k > 0; k-- {
		values[k-1] = (2*float64(k)/x)*values[k] - values[k+1]
	}
	total := 0.0
	for k := 0; k <= m; k += 2 {
		total += 2 * values[k]
	}
	total -= values[0]
	return values[n] / total
}

// besselY 对应 C# SpecialFunctions.BesselY（整数阶第二类贝塞尔函数）。
func besselY(n int, x float64) float64 {
	if n < 0 {
		n = -n
	}
	if n == 0 {
		return besselY0(x)
	}
	if n == 1 {
		return besselY1(x)
	}
	// 阶数极大时 Y_n 已上溢，直接返回 +Inf（调用方转成函数错误），避免超长循环
	if n > 100000 {
		return math.Inf(1)
	}
	y0 := besselY0(x)
	y1 := besselY1(x)
	result := 0.0
	for k := 1; k < n; k++ {
		result = (2*float64(k)/x)*y1 - y0
		y0, y1 = y1, result
		if math.IsInf(result, 0) || math.IsNaN(result) {
			return result
		}
	}
	return y1
}
