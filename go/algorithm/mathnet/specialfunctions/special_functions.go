// Erfc 返回互补误差函数 erfc(x)。
func Erfc(x float64) float64 {
	if x == 0 {
		return 1
	}

	return erfImp(x, true)
}

func erfImp(z float64, invert bool) float64 {
	if z < 0 {
		if !invert {
			return -erfImp(-z, false)
		}

		if z < -0.5 {
			return 2 - erfImp(-z, true)
		}

		return 1 + erfImp(-z, false)
	}

	var result float64

	if z < 0.5 {
		if z < 0.0000000001 {
			result = (z * 1.125) + (z * 0.003379167095512573896158903121545171688)
		} else {
			result = (z * 1.125) + (z * Polynomial(z, erfImpAn) / Polynomial(z, erfImpAd))
		}
	} else if (z < 110) || ((z < 110) && invert) {
		invert = !invert
		var r, b float64
		switch {
		case z < 0.75:
			r = Polynomial(z-0.5, erfImpBn) / Polynomial(z-0.5, erfImpBd)
			b = 0.3440242112
		case z < 1.25:
			r = Polynomial(z-0.75, erfImpCn) / Polynomial(z-0.75, erfImpCd)
			b = 0.419990927
		case z < 2.25:
			r = Polynomial(z-1.25, erfImpDn) / Polynomial(z-1.25, erfImpDd)
			b = 0.4898625016
		case z < 3.5:
			r = Polynomial(z-2.25, erfImpEn) / Polynomial(z-2.25, erfImpEd)
			b = 0.5317370892
		case z < 5.25:
			r = Polynomial(z-3.5, erfImpFn) / Polynomial(z-3.5, erfImpFd)
			b = 0.5489973426
		case z < 8:
			r = Polynomial(z-5.25, erfImpGn) / Polynomial(z-5.25, erfImpGd)
			b = 0.5571740866
		case z < 11.5:
			r = Polynomial(z-8, erfImpHn) / Polynomial(z-8, erfImpHd)
			b = 0.5609807968
		case z < 17:
			r = Polynomial(z-11.5, erfImpIn) / Polynomial(z-11.5, erfImpId)
			b = 0.5626493692
		case z < 24:
			r = Polynomial(z-17, erfImpJn) / Polynomial(z-17, erfImpJd)
			b = 0.5634598136
		case z < 38:
			r = Polynomial(z-24, erfImpKn) / Polynomial(z-24, erfImpKd)
			b = 0.5638477802
		case z < 60:
			r = Polynomial(z-38, erfImpLn) / Polynomial(z-38, erfImpLd)
			b = 0.5640528202
		case z < 85:
			r = Polynomial(z-60, erfImpMn) / Polynomial(z-60, erfImpMd)
			b = 0.5641309023
		default:
			r = Polynomial(z-85, erfImpNn) / Polynomial(z-85, erfImpNd)
			b = 0.5641584396
		}

		g := math.Exp(-z*z) / z
		result = (g * b) + (g * r)
	} else {
		result = 0
		invert = !invert
	}

	if invert {
		result = 1 - result
	}

	return result
}

// ErfcInv 返回 erfc 的反函数。
func ErfcInv(z float64) float64 {
	if z <= 0.0 {
		return decimalMaxValue
	}

	if z >= 2.0 {
		return -decimalMaxValue
	}

	var p, q, s float64
	if z > 1 {
		q = 2 - z
		p = 1 - q
		s = -1
	} else {
		p = 1 - z
		q = z
		s = 1
	}

	return erfInvImpl(p, q, s)
}

func erfInvImpl(p, q, s float64) float64 {
	var result float64

	if p <= 0.5 {
		const y = 0.0891314744949340820313
		g := p * (p + 10)
		r := Polynomial(p, ervInvImpAn) / Polynomial(p, ervInvImpAd)
		result = (g * y) + (g * r)
	} else if q >= 0.25 {
		const y = 2.249481201171875
		g := math.Sqrt(-2 * math.Log(q))
		xs := q - 0.25
		r := Polynomial(xs, ervInvImpBn) / Polynomial(xs, ervInvImpBd)
		result = g / (y + r)
	} else {
		x := math.Sqrt(-math.Log(q))
		switch {
		case x < 3:
			const y = 0.807220458984375
			xs := x - 1.125
			r := Polynomial(xs, ervInvImpCn) / Polynomial(xs, ervInvImpCd)
			result = (y * x) + (r * x)
		case x < 6:
			const y = 0.93995571136474609375
			xs := x - 3
			r := Polynomial(xs, ervInvImpDn) / Polynomial(xs, ervInvImpDd)
			result = (y * x) + (r * x)
		case x < 18:
			const y = 0.98362827301025390625
			xs := x - 6
			r := Polynomial(xs, ervInvImpEn) / Polynomial(xs, ervInvImpEd)
			result = (y * x) + (r * x)
		case x < 44:
			const y = 0.99714565277099609375
			xs := x - 18
			r := Polynomial(xs, ervInvImpFn) / Polynomial(xs, ervInvImpFd)
			result = (y * x) + (r * x)
		default:
			const y = 0.99941349029541015625
			xs := x - 44
			r := Polynomial(xs, ervInvImpGn) / Polynomial(xs, ervInvImpGd)
			result = (y * x) + (r * x)
		}
	}

	return s * result
}

// ErfInv 返回 erf 的反函数。
func ErfInv(z float64) float64 {
	if z == 0.0 {
		return 0.0
	}

	if z >= 1.0 {
		return decimalMaxValue
	}

	if z <= -1.0 {
		return -decimalMaxValue
	}

	var p, q, s float64
	if z < 0 {
		p = -z
		q = 1 - p
		s = -1
	} else {
		p = z
		q = 1 - z
		s = 1
	}

	return erfInvImpl(p, q, s)
}

// Erf 返回误差函数 erf(x)。
func Erf(x float64) float64 {
	if x == 0 {
		return 0
	}

	return erfImp(x, false)
}
